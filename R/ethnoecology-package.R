#' ethnoecology: Quantitative Ethnoecology Analysis and Landscape Knowledge Modeling
#'
#' The ethnoecology package provides tools for quantifying Traditional Ecological
#' Knowledge (LEK) in landscape and ecosystem contexts. It implements quantitative
